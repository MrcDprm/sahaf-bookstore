    public static List<Product> Products(IReadOnlyList<Category> categories)
    {
        var now = DateTime.UtcNow;
        return Books.Select((b, i) =>
        {
            var price = RoundTo5(95 + b.Pages * 0.28m);
            // Every third book is on sale, so the store has a "deals" shelf.
            var listPrice = i % 3 == 0 ? RoundTo5(price * (1.2m + i % 4 * 0.05m)) : price;
            return new Product
            {
                Title = b.Title,
                TitleEn = b.TitleEn,
                Author = b.Author,
                Year = b.Year,
                PageCount = b.Pages,
                Description = b.Description,
                DescriptionEn = b.DescriptionEn,
                ListPrice = listPrice,
                Price = price,
                Price50 = RoundTo5(price * 0.9m),
                Price100 = RoundTo5(price * 0.82m),
                IsFeatured = b.Featured,
                CategoryId = categories[b.Category - 1].Id,
                CreatedAt = now.AddHours(-i * 9),
            };
        }).ToList();
    }

    private static decimal RoundTo5(decimal value) => Math.Round(value / 5m, MidpointRounding.AwayFromZero) * 5m;
